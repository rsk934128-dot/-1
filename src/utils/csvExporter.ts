import { Order, FoodItem } from '../types';
import { HOTEL_INFO } from '../data/initialData';

export interface WeeklyTrendItem {
  dayBn: string;
  dayEn: string;
  orders: number;
  revenue: number;
  bkash: number;
  cash: number;
  isToday?: boolean;
}

/**
 * Clean and escape strings for CSV output
 */
const escapeCsvCell = (val: string | number | undefined | null): string => {
  if (val === undefined || val === null) return '""';
  const str = String(val).replace(/"/g, '""');
  return `"${str}"`;
};

/**
 * Export current week's order and revenue summary into a formatted CSV file
 */
export const exportWeeklySummaryCsv = (
  orders: Order[],
  weeklyTrends: WeeklyTrendItem[],
  foodItems: FoodItem[],
  adminEmail: string,
  lang: 'bn' | 'en' = 'bn'
): void => {
  const currentDateStr = new Date().toISOString().split('T')[0];
  const currentTimeFormatted = new Date().toLocaleString('en-US');

  // Compute grand totals
  const totalWeeklyRevenue = weeklyTrends.reduce((sum, item) => sum + item.revenue, 0);
  const totalWeeklyOrders = weeklyTrends.reduce((sum, item) => sum + item.orders, 0);
  const totalWeeklyBkash = weeklyTrends.reduce((sum, item) => sum + item.bkash, 0);
  const totalWeeklyCash = weeklyTrends.reduce((sum, item) => sum + item.cash, 0);

  const lines: string[] = [];

  // ==========================================
  // 1. BUSINESS & REPORT METADATA HEADER
  // ==========================================
  lines.push(escapeCsvCell(`${HOTEL_INFO.nameBn} (${HOTEL_INFO.nameEn}) - Weekly Business & Revenue Summary`));
  lines.push(`${escapeCsvCell('Location')},${escapeCsvCell(HOTEL_INFO.locationBn)}`);
  lines.push(`${escapeCsvCell('Proprietor')},${escapeCsvCell(HOTEL_INFO.proprietorBn)}`);
  lines.push(`${escapeCsvCell('Contact Numbers')},${escapeCsvCell(`${HOTEL_INFO.phone1}, ${HOTEL_INFO.phone2}`)}`);
  lines.push(`${escapeCsvCell('Report Generation Date')},${escapeCsvCell(currentTimeFormatted)}`);
  lines.push(`${escapeCsvCell('Generated By Admin')},${escapeCsvCell(adminEmail)}`);
  lines.push(''); // Empty line

  // ==========================================
  // 2. WEEKLY 7-DAY REVENUE & ORDER BREAKDOWN
  // ==========================================
  lines.push(escapeCsvCell('--- SECTION 1: 7-DAY WEEKLY REVENUE & ORDER TRENDS ---'));
  lines.push([
    escapeCsvCell('Day (বাংলা)'),
    escapeCsvCell('Day (English)'),
    escapeCsvCell('Total Orders'),
    escapeCsvCell('Total Revenue (BDT ৳)'),
    escapeCsvCell('bKash / Digital (৳)'),
    escapeCsvCell('Cash in Hand (৳)'),
    escapeCsvCell('Average Order Value (৳)'),
    escapeCsvCell('Status / Type'),
  ].join(','));

  weeklyTrends.forEach((item) => {
    const avg = item.orders > 0 ? Math.round(item.revenue / item.orders) : 0;
    lines.push([
      escapeCsvCell(item.dayBn),
      escapeCsvCell(item.dayEn),
      escapeCsvCell(item.orders),
      escapeCsvCell(item.revenue),
      escapeCsvCell(item.bkash),
      escapeCsvCell(item.cash),
      escapeCsvCell(avg),
      escapeCsvCell(item.isToday ? 'Live / Current Day' : 'Recorded Baseline'),
    ].join(','));
  });

  // Weekly Totals Row
  lines.push([
    escapeCsvCell('TOTAL WEEKLY SUMMARY'),
    escapeCsvCell('All 7 Days'),
    escapeCsvCell(totalWeeklyOrders),
    escapeCsvCell(totalWeeklyRevenue),
    escapeCsvCell(totalWeeklyBkash),
    escapeCsvCell(totalWeeklyCash),
    escapeCsvCell(totalWeeklyOrders > 0 ? Math.round(totalWeeklyRevenue / totalWeeklyOrders) : 0),
    escapeCsvCell('Grand Total'),
  ].join(','));

  lines.push(''); // Empty line
  lines.push(''); // Empty line

  // ==========================================
  // 3. LIVE ORDER TRANSACTION LEDGER
  // ==========================================
  lines.push(escapeCsvCell('--- SECTION 2: LIVE ORDERS DETAILED TRANSACTION LEDGER ---'));
  lines.push([
    escapeCsvCell('Order ID'),
    escapeCsvCell('Created At'),
    escapeCsvCell('Customer Name'),
    escapeCsvCell('Customer Phone'),
    escapeCsvCell('Order Type'),
    escapeCsvCell('Table / Delivery Address'),
    escapeCsvCell('Items Summary'),
    escapeCsvCell('Subtotal (৳)'),
    escapeCsvCell('Delivery Fee (৳)'),
    escapeCsvCell('Net Total (৳)'),
    escapeCsvCell('Payment Method'),
    escapeCsvCell('Payment Status'),
    escapeCsvCell('Transaction ID'),
    escapeCsvCell('Order Status'),
    escapeCsvCell('Special Instructions'),
  ].join(','));

  orders.forEach((ord) => {
    const itemsDescription = ord.items
      .map((it) => {
        const name = lang === 'bn' ? it.food.nameBn : it.food.nameEn;
        const portion = it.selectedPortion ? ` (${it.selectedPortion.labelBn})` : '';
        return `${name}${portion} x${it.quantity} (৳${it.food.price * it.quantity})`;
      })
      .join('; ');

    const orderTypeLabel = 
      ord.orderType === 'dine_in' 
        ? `Dine-In (Table #${ord.tableNumber || 'N/A'})` 
        : ord.orderType === 'parcel'
        ? 'Counter Parcel'
        : `Home Delivery (${ord.deliveryAddress || 'Station Area'})`;

    lines.push([
      escapeCsvCell(`#${ord.id}`),
      escapeCsvCell(ord.createdAt),
      escapeCsvCell(ord.customerName),
      escapeCsvCell(ord.customerPhone),
      escapeCsvCell(orderTypeLabel),
      escapeCsvCell(ord.tableNumber ? `Table ${ord.tableNumber}` : ord.deliveryAddress || 'Counter'),
      escapeCsvCell(itemsDescription),
      escapeCsvCell(ord.subtotal),
      escapeCsvCell(ord.deliveryFee),
      escapeCsvCell(ord.total),
      escapeCsvCell(ord.paymentMethod.toUpperCase()),
      escapeCsvCell(ord.paymentStatus),
      escapeCsvCell(ord.transactionId || 'N/A'),
      escapeCsvCell(ord.status.toUpperCase()),
      escapeCsvCell(ord.specialNote || ''),
    ].join(','));
  });

  lines.push(''); // Empty line
  lines.push(''); // Empty line

  // ==========================================
  // 4. MENU ITEMS & STOCK SNAPSHOT
  // ==========================================
  lines.push(escapeCsvCell('--- SECTION 3: MENU INVENTORY & PRICE DIRECTORY ---'));
  lines.push([
    escapeCsvCell('Item ID'),
    escapeCsvCell('Item Name (বাংলা)'),
    escapeCsvCell('Item Name (English)'),
    escapeCsvCell('Category'),
    escapeCsvCell('Price per Unit (৳)'),
    escapeCsvCell('Unit Type'),
    escapeCsvCell('In Stock Status'),
    escapeCsvCell('Prep Time (Mins)'),
  ].join(','));

  foodItems.forEach((food) => {
    lines.push([
      escapeCsvCell(food.id),
      escapeCsvCell(food.nameBn),
      escapeCsvCell(food.nameEn),
      escapeCsvCell(food.category),
      escapeCsvCell(food.price),
      escapeCsvCell(food.unitBn),
      escapeCsvCell(food.inStock ? 'Available / In Stock' : 'Out of Stock'),
      escapeCsvCell(food.preparationTimeMinutes || 10),
    ].join(','));
  });

  // UTF-8 BOM (\uFEFF) to make Excel properly render Bengali unicode characters
  const csvContent = '\uFEFF' + lines.join('\r\n');
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);

  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `hotel_al_sheikh_farid_weekly_summary_${currentDateStr}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
};
